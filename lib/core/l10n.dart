/// The 7 languages from the reference game, in the order the language
/// button cycles through them.
const kLanguages = ['en', 'zh', 'fr', 'de', 'ja', 'ko', 'es'];

/// Picks the device language on first launch if we support it.
String defaultLanguage() {
  final code = PlatformDispatcher.instance.locale.languageCode;
  return kLanguages.contains(code) ? code : 'en';
}

String nextLanguage(String current) =>
    kLanguages[(kLanguages.indexOf(current) + 1) % kLanguages.length];

/// Translates [key] into the current language. `{n}` in the text is
/// replaced by [n].
String tr(String key, [Object? n]) {
  final s = _strings[Save.I.lang]?[key] ?? _strings['en']![key] ?? key;
  return n == null ? s : s.replaceAll('{n}', '$n');
}

